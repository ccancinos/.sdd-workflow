#!/usr/bin/env bash
#
# skill-registry.sh — build the skill registry index the orchestrator reads.
#
# Scans skill roots for */SKILL.md, parses the `name` and `description` from each frontmatter, and
# writes an index to .sdd-workflow/.skill-registry.md. The orchestrator reads this index at the
# start of an SDD session so it can pass exact SKILL.md paths to sub-agents.
#
# Run it manually after you add/remove/rename skills. Nothing outside .sdd-workflow/ is written.
#
# Scan order (first match by skill name wins — duplicates are silently dropped):
#   1. <root>/.claude/skills/     — user skills installed for Claude Code
#   2. <root>/.opencode/skills/   — user skills installed for OpenCode
#   3. .sdd-workflow/common/skills/extensions/  — toolkit extension skills (canonical source)
#
# Phase skills (.sdd-workflow/common/skills/phases/) are intentionally excluded — the orchestrator
# loads them via hardcoded paths, not via the registry.
#
# Usage: .sdd-workflow/bin/skill-registry.sh

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SDD_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
ROOT="$(cd "$SDD_DIR/.." && pwd)"
OUT="$SDD_DIR/.skill-registry.md"

# Extract a single frontmatter scalar (name/description) from a SKILL.md.
# Handles `key: value`, quoted values, and YAML `>` / `|` folded blocks (first line only).
fm_field() {
  local file="$1" key="$2"
  awk -v key="$key" '
    NR==1 && $0!="---" { exit }             # no frontmatter
    NR==1 { infm=1; next }
    infm && $0=="---" { exit }
    infm {
      # match "key:" at column 0
      if ($0 ~ "^" key ":") {
        line=$0
        sub("^" key ":[ \t]*", "", line)
        # folded/literal block: value continues on next indented line
        if (line=="" || line==">" || line=="|" || line==">-" || line=="|-") {
          getline nextline
          gsub(/^[ \t]+/, "", nextline)
          print nextline
          exit
        }
        gsub(/^"/, "", line); gsub(/"$/, "", line)
        gsub(/^'"'"'/, "", line); gsub(/'"'"'$/, "", line)
        print line
        exit
      }
    }
  ' "$file"
}

declare -a ROWS=()
declare -A SEEN=()

scan_root() {
  local skills_dir="$1" scope="$2"
  [[ -d "$skills_dir" ]] || return 0
  local skill_md name desc dir
  for skill_md in "$skills_dir"/*/SKILL.md; do
    [[ -f "$skill_md" ]] || continue
    dir="$(basename "$(dirname "$skill_md")")"
    name="$(fm_field "$skill_md" name)"; name="${name:-$dir}"
    [[ -n "${SEEN[$name]:-}" ]] && continue
    SEEN[$name]=1
    desc="$(fm_field "$skill_md" description)"; desc="${desc:-（no description）}"
    # Store the path relative to root when possible for portability.
    local relpath="${skill_md#$ROOT/}"
    ROWS+=("| \`$name\` | $scope | $desc | \`$relpath\` |")
  done
}

scan_root "$ROOT/.claude/skills"                    "project"
scan_root "$ROOT/.opencode/skills"                  "project"
scan_root "$SDD_DIR/common/skills/extensions"       "toolkit"

{
  echo "# Skill Registry"
  echo ""
  echo "_Generated by \`.sdd-workflow/bin/skill-registry.sh\`. Do not edit by hand._"
  echo ""
  echo "The orchestrator reads this index and passes the exact \`SKILL.md\` path to each sub-agent."
  echo "Phase skills (\`common/skills/phases/\`) are excluded — the orchestrator loads them via hardcoded paths."
  echo ""
  echo "| Skill | Scope | Trigger / description | Path |"
  echo "| --- | --- | --- | --- |"
  if [[ ${#ROWS[@]} -gt 0 ]]; then
    printf '%s\n' "${ROWS[@]}" | sort
  fi
} > "$OUT"

echo "Wrote $OUT (${#ROWS[@]} skills indexed)."
